function calcularPromedioIntegral() {
    const valores = [];
    
    for (let i = 1; i <= 3; i++) {
        const span = document.getElementById(`evalValueInt${i}`);
        if (span) {
            const texto = span.textContent;
            const valor = parseInt(texto);
            if (!isNaN(valor)) {
                valores.push(valor);
            }
        }
    }
    
    if (valores.length > 0) {
        const promedio = (valores.reduce((a, b) => a + b) / valores.length).toFixed(1);
        document.getElementById(\'evalAverageIntegral\').textContent = promedio;
    }
}

