// Actualizar antiderivada CORREGIDA
function actualizarAntiderivada(funcionStr) {
    let antiderivada = "";
    let detalle = "";
    
    // Determinar antiderivada según la función (simplificado)
    const funcionLower = funcionStr.toLowerCase().replace(/\\s/g, \'\');
    
    if (funcionLower.includes("x^2") || funcionLower.includes("x**2")) {
        antiderivada = "\\\\frac{x^3}{3} + C";
        detalle = "Para x², la antiderivada es x³/3";
    } else if (funcionLower.includes("x^3") && funcionLower.includes("-3*x")) {
        antiderivada = "\\\\frac{x^4}{4} - \\\\frac{3x^2}{2} + C";
        detalle = "Integral de x³ - 3x";
    } else if (funcionLower.includes("sin(x)") || funcionLower.includes("sinx")) {
        antiderivada = "-\\\\cos(x) + C";
        detalle = "La derivada de -cos(x) es sin(x)";
    } else if (funcionLower.includes("cos(x)") || funcionLower.includes("cosx")) {
        antiderivada = "\\\\sin(x) + C";
        detalle = "La derivada de sin(x) es cos(x)";
    } else if (funcionLower.includes("e^x") || funcionLower.includes("exp(x)")) {
        antiderivada = "e^x + C";
        detalle = "La derivada de eˣ es eˣ";
    } else if (funcionLower.includes("ln(x)") || funcionLower.includes("log(x)")) {
        antiderivada = "x\\\\ln(x) - x + C";
        detalle = "Integral por partes: ∫ln(x)dx = x·ln(x) - x + C";
    } else if (funcionLower.includes("1/x") || funcionLower === "x^-1") {
        antiderivada = "\\\\ln|x| + C";
        detalle = "Para 1/x, la antiderivada es ln|x|";
    } else {
        antiderivada = "F(x) + C";
        detalle = "Función primitiva más constante de integración";
    }
    
    // Actualizar en la interfaz CORREGIDO
    const formulaElement = document.getElementById(\'formula-antiderivada\');
    if (formulaElement) {
        formulaElement.innerHTML = `\\\\[ \\\\int ${funcionStr.replace(/\\*/g, \'\')} \\\\, dx = ${antiderivada} \\\\]`;
    }
    
    document.getElementById(\'detalle-antiderivada\').innerHTML = detalle;
}

