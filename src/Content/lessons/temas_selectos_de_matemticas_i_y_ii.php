// Calcular integral numérica
function calcularIntegralNumerica(puntos, a, b) {
    const metodo = document.getElementById(\'metodo-integracion\').value;
    const n = puntos.length - 1;
    let integral = 0;
    let areaPositiva = 0;
    let areaNegativa = 0;
    
    if (metodo === \'trapecio\') {
        // Método del trapecio
        for (let i = 0; i < n; i++) {
            const x1 = puntos[i].x;
            const x2 = puntos[i+1].x;
            const y1 = puntos[i].y;
            const y2 = puntos[i+1].y;
            const dx = x2 - x1;
            
            // Integral usando trapecio
            integral += (y1 + y2) * dx / 2;
            
            // Áreas positivas y negativas
            if (y1 >= 0 && y2 >= 0) {
                areaPositiva += Math.abs((y1 + y2) * dx / 2);
            } else if (y1 <= 0 && y2 <= 0) {
                areaNegativa += Math.abs((y1 + y2) * dx / 2);
            } else {
                // La línea cruza el eje x
                const xCorte = x1 - y1 * (x2 - x1) / (y2 - y1);
                const area1 = Math.abs(y1 * (xCorte - x1) / 2);
                const area2 = Math.abs(y2 * (x2 - xCorte) / 2);
                
                if (y1 >= 0) {
                    areaPositiva += area1;
                    areaNegativa += area2;
                } else {
                    areaPositiva += area2;
                    areaNegativa += area1;
                }
            }
        }
    } else if (metodo === \'simpson\') {
        // Regla de Simpson (requiere n par)
        const nSimpson = n % 2 === 0 ? n : n - 1;
        const dx = (b - a) / nSimpson;
        
        // Calcular usando fórmula de Simpson
        for (let i = 0; i <= nSimpson; i++) {
            const x = a + i * dx;
            const y = puntos[Math.floor(i * n / nSimpson)].y;
            
            let factor = 1;
            if (i === 0 || i === nSimpson) {
                factor = 1;
            } else if (i % 2 === 1) {
                factor = 4;
            } else {
                factor = 2;
            }
            
            integral += factor * y;
            
            // Para áreas, usar método más simple
            if (y >= 0) {
                areaPositiva += Math.abs(y * dx);
            } else {
                areaNegativa += Math.abs(y * dx);
            }
        }
        
        integral *= dx / 3;
        areaPositiva /= 2; // Ajustar para Simpson
        areaNegativa /= 2;
    } else {
        // Sumas de Riemann (derecha)
        const dx = (b - a) / n;
        
        for (let i = 1; i <= n; i++) {
            const x = a + i * dx;
            const y = puntos[i].y;
            
            integral += y * dx;
            
            if (y >= 0) {
                areaPositiva += Math.abs(y * dx);
            } else {
                areaNegativa += Math.abs(y * dx);
            }
        }
    }
    
    return {
        definida: integral,
        areaPositiva: areaPositiva,
        areaNegativa: areaNegativa,
        areaTotal: areaPositiva + areaNegativa
    };
}

