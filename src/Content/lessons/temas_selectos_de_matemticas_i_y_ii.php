function calcularValorPunto() {
    const puntoInput = document.getElementById(\'puntoEvaluacion\');
    const funcionInput = document.getElementById(\'funcionInput\').value.trim();
    
    if (!funcionInput || !puntoInput.value) {
        mostrarNotificacion(\'Ingresa una función y un valor para x\', \'warning\');
        return;
    }
    
    try {
        const punto = parseFloat(puntoInput.value);
        
        // Preprocesar función
        const { procesada } = preprocesarFuncion(funcionInput);
        
        if (typeof math === \'undefined\') {
            throw new Error(\'Math.js no está disponible\');
        }
        
        // Crear ámbito para evaluación
        const scope = { x: punto };
        
        // Evaluar función original
        const nodeFuncion = math.parse(procesada);
        const valorFuncion = nodeFuncion.evaluate(scope);
        
        // Calcular derivada y evaluarla
        const nodeDerivada = math.derivative(nodeFuncion, \'x\');
        const valorDerivada = nodeDerivada.evaluate(scope);
        
        // Mostrar resultados
        document.getElementById(\'valorFuncion\').textContent = valorFuncion.toFixed(5);
        document.getElementById(\'valorDerivada\').textContent = valorDerivada.toFixed(5);
        document.getElementById(\'pendiente\').textContent = valorDerivada.toFixed(5);
        
        // Interpretación
        let interpretacion = \'\';
        if (valorDerivada > 0) {
            interpretacion = `📈 La función crece (pendiente positiva: ${valorDerivada.toFixed(3)})`;
        } else if (valorDerivada < 0) {
            interpretacion = `📉 La función decrece (pendiente negativa: ${valorDerivada.toFixed(3)})`;
        } else {
            interpretacion = `⚖️ Punto crítico (pendiente cero)`;
        }
        
        mostrarNotificacion(interpretacion, \'info\');
        
    } catch (error) {
        console.error(\'Error evaluando en punto:\', error);
        document.getElementById(\'valorFuncion\').textContent = \'Error\';
        document.getElementById(\'valorDerivada\').textContent = \'Error\';
        document.getElementById(\'pendiente\').textContent = \'Error\';
        
        mostrarNotificacion(`Error al evaluar: ${error.message}`, \'error\');
    }
}

