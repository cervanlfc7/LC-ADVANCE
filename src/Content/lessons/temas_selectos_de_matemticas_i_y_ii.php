function preprocesarFuncion(input) {
    if (!input) return \'\';
    
    // Guardar función original para mostrar
    const funcionOriginal = input;
    
    // Reemplazar ln, Ln, LN por log (Math.js usa log como logaritmo natural)
    let procesada = input
        .replace(/\\bln\\(/gi, \'log(\')
        .replace(/\\bln\\b/gi, \'log\')
        .replace(/\\bLn\\(/gi, \'log(\')
        .replace(/\\bLN\\(/gi, \'log(\');
    
    // Reemplazar ^ por ** (sintaxis de Math.js)
    procesada = procesada.replace(/\\^/g, \'**\');
    
    // Reemplazar e^x por exp(x)
    procesada = procesada.replace(/e\\^\\(([^)]+)\\)/g, \'exp($1)\');
    procesada = procesada.replace(/e\\^(\\w+)/g, \'exp($1)\');
    
    return {
        original: funcionOriginal,
        procesada: procesada
    };
}

function calcularDerivadaCompleta() {
    const inputElement = document.getElementById(\'funcionInput\');
    const funcionInput = inputElement.value.trim();
    const resultadoElement = document.getElementById(\'resultadoPrincipal\');
    const estadoElement = document.getElementById(\'estadoCalculo\');
    const funcionDisplay = document.getElementById(\'funcionOriginalDisplay\');
    const derivadaDisplay = document.getElementById(\'derivadaDisplay\');
    
    if (!funcionInput) {
        resultadoElement.innerHTML = \'<div class="error-resultado">❌ Por favor, ingresa una función</div>\';
        estadoElement.textContent = \'Error: función vacía\';
        estadoElement.className = \'resultado-estado error\';
        return;
    }
    
    // Actualizar estado
    estadoElement.textContent = \'Calculando...\';
    estadoElement.className = \'resultado-estado calculando\';
    
    try {
        // Preprocesar función
        const { original, procesada } = preprocesarFuncion(funcionInput);
        
        // Verificar si Math.js está cargado
        if (typeof math === \'undefined\') {
            throw new Error(\'Math.js no está cargado. Recarga la página.\');
        }
        
        // Parsear y derivar
        console.log(\'Función procesada:\', procesada);
        const node = math.parse(procesada);
        const derivada = math.derivative(node, \'x\');
        
        // Simplificar la derivada
        const derivadaSimplificada = math.simplify(derivada.toString());
        
        // Mostrar resultados
        funcionDisplay.textContent = `f(x) = ${original}`;
        derivadaDisplay.innerHTML = `f\'(x) = <strong>${derivadaSimplificada.toString()}</strong>`;
        
        // Actualizar estado
        estadoElement.textContent = \'✅ Derivada calculada correctamente\';
        estadoElement.className = \'resultado-estado success\';
        
        // Mostrar pasos
        mostrarPasosDerivada(original, derivadaSimplificada.toString());
        
        // Evaluar en punto por defecto
        setTimeout(() => calcularValorPunto(), 500);
        
    } catch (error) {
        console.error(\'Error calculando derivada:\', error);
        
        funcionDisplay.textContent = `f(x) = ${funcionInput}`;
        derivadaDisplay.innerHTML = \'<span class="error-text">Error calculando derivada</span>\';
        
        estadoElement.textContent = `❌ Error: ${error.message}`;
        estadoElement.className = \'resultado-estado error\';
        
        // Mostrar sugerencias de error
        mostrarSugerenciasError(error, funcionInput);
    }
}

