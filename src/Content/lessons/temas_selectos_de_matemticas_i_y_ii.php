    });
    
    const feedbackDiv = document.getElementById(\'solucionFeedback\');
    
    if (correcto) {
        feedbackDiv.innerHTML = `
            <div class="feedback-excelente">
                <h4>✅ ¡Correcto! Paso ${paso} completado</h4>
                <p>Solución aceptada. Continúa con el siguiente paso.</p>
            </div>
        `;
        textarea.style.borderColor = \'#39FF14\';
        mostrarNotificacion(`Paso ${paso} verificado correctamente`, \'success\');
    } else {
        feedbackDiv.innerHTML = `
            <div class="feedback-error">
                <h4>❌ Revisa el paso ${paso}</h4>
                <p>Tu respuesta no coincide con la solución esperada.</p>
                <p><strong>Sugerencia:</strong> ${getSugerenciaPaso(paso)}</p>
            </div>
        `;
