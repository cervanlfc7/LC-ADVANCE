// Función auxiliar para preparar función para evaluación
function prepararFuncionParaEval(funcionStr) {
    // Convertir notación matemática a notación JavaScript
    let func = funcionStr
        .replace(/\\^/g, \'**\')  // x^2 -> x**2
        .replace(/(\\d)([a-zA-Z(])/g, \'$1*$2\')  // 3x -> 3*x
        .replace(/([a-zA-Z)])(\\d)/g, \'$1*$2\')   // x3 -> x*3
        .replace(/([a-zA-Z)])([a-zA-Z(])/g, \'$1*$2\'); // xy -> x*y
    
    // Manejar funciones especiales
    func = func.replace(/ln\\(/g, \'Math.log(\');
    func = func.replace(/log\\(/g, \'Math.log10(\');
    func = func.replace(/sin\\(/g, \'Math.sin(\');
    func = func.replace(/cos\\(/g, \'Math.cos(\');
    func = func.replace(/tan\\(/g, \'Math.tan(\');
    func = func.replace(/sqrt\\(/g, \'Math.sqrt(\');
    func = func.replace(/exp\\(/g, \'Math.exp(\');
    func = func.replace(/e\\^/g, \'Math.exp(\');
    func = func.replace(/pi/g, \'Math.PI\');
    func = func.replace(/e(?![a-zA-Z])/g, \'Math.E\'); // e solo, no en exp
    
    return func;
}

