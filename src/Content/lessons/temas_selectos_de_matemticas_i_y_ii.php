function actualizarIntervalosConcavidad(funcion, xMin, xMax) {
    const puntosAnalisis = [];
    const paso = (xMax - xMin) / 100;
    
    let intervaloActual = { inicio: xMin, tipo: null };
    
    for (let x = xMin; x <= xMax; x += paso) {
        if (!funcion.dominio(x)) continue;
        
        const fprime2 = funcion.fprime2(x);
        
        if (isNaN(fprime2)) {
            // Discontinuidad
            if (intervaloActual.tipo !== null) {
                intervaloActual.fin = x;
                puntosAnalisis.push(intervaloActual);
            }
            intervaloActual = { inicio: x, tipo: null };
            continue;
        }
        
        let tipo = null;
        if (fprime2 > 0.001) {
            tipo = \'arriba\';
        } else if (fprime2 < -0.001) {
            tipo = \'abajo\';
        } else {
            tipo = \'cero\';
        }
        
        if (intervaloActual.tipo === null) {
            intervaloActual.tipo = tipo;
        } else if (intervaloActual.tipo !== tipo) {
            // Cambio de concavidad
            intervaloActual.fin = x;
            puntosAnalisis.push(intervaloActual);
            intervaloActual = { inicio: x, tipo: tipo };
        }
    }
    
    // Agregar último intervalo
    if (intervaloActual.tipo !== null) {
        intervaloActual.fin = xMax;
        puntosAnalisis.push(intervaloActual);
    }
    
    // Generar HTML
    let html = \'<div class="intervalos-lista">\';
    
    if (puntosAnalisis.length === 0) {
        html += \'<span style="color: #FF6B6B">No se pudo determinar la concavidad.</span>\';
    } else {
        puntosAnalisis.forEach(intervalo => {
            let icono = \'↔️\';
            let color = \'#666\';
            let texto = \'Indeterminado\';
            
            if (intervalo.tipo === \'arriba\') {
                icono = \'😊\';
                color = \'#39FF14\';
                texto = \'Cóncava hacia arriba\';
            } else if (intervalo.tipo === \'abajo\') {
                icono = \'🙁\';
                color = \'#FF6B6B\';
                texto = \'Cóncava hacia abajo\';
            } else if (intervalo.tipo === \'cero\') {
                icono = \'⚡\';
                color = \'#FFFF00\';
                texto = \'Posible inflexión\';
            }
            
            html += `
                <div class="intervalo-item" style="border-left-color: ${color}">
                    <span class="intervalo-icon">${icono}</span>
                    <div class="intervalo-info">
                        <strong>[${intervalo.inicio.toFixed(2)}, ${intervalo.fin.toFixed(2)}]</strong><br>
                        ${texto}
                    </div>
                </div>
            `;
        });
    }
    
    html += \'</div>\';
    document.getElementById(\'intervalos-concavidad\').innerHTML = html;
}

