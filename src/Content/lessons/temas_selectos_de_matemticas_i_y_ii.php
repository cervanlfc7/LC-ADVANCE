function encontrarPuntosInflexion(funcion, xMin, xMax, precision = 0.01) {
    const puntos = [];
    let signoAnterior = null;
    
    for (let x = xMin; x <= xMax; x += precision) {
        if (!funcion.dominio(x)) continue;
        
        const valorFprime2 = funcion.fprime2(x);
        
        if (isNaN(valorFprime2)) continue;
        
        const signoActual = Math.sign(valorFprime2);
        
        // Verificar cambio de signo (incluyendo cuando f\'\' no existe)
        if (signoAnterior !== null && signoAnterior !== 0 && signoActual !== 0) {
            if (signoAnterior !== signoActual) {
                // Buscar punto exacto usando interpolación
                const xExacto = encontrarCeroPorBiseccion(
                    x - precision, x, 
                    xTest => funcion.fprime2(xTest),
                    precision/10
                );
                
                if (xExacto !== null && !puntos.some(p => Math.abs(p - xExacto) < 0.1)) {
                    puntos.push(parseFloat(xExacto.toFixed(3)));
                }
            }
        }
        
        signoAnterior = signoActual;
    }
    
    return puntos;
}

function encontrarCeroPorBiseccion(a, b, funcion, tolerancia = 0.001) {
    let izquierda = a;
    let derecha = b;
    
    // Verificar que haya cambio de signo
    const fA = funcion(izquierda);
    const fB = funcion(derecha);
    
    if (Math.sign(fA) === Math.sign(fB)) {
        return null;
    }
    
    for (let i = 0; i < 50; i++) {
        const medio = (izquierda + derecha) / 2;
        const fMedio = funcion(medio);
        
        if (Math.abs(fMedio) < tolerancia) {
            return medio;
        }
        
        if (Math.sign(fMedio) === Math.sign(fA)) {
            izquierda = medio;
        } else {
            derecha = medio;
        }
    }
    
    return (izquierda + derecha) / 2;
}

function encontrarPuntosCriticos() {
    const select = document.getElementById(\'funcion-select\');
    const funcionKey = select.value;
    const funcion = funcionesMatematicas[funcionKey];
    
    if (!funcion) return;
    
    const xMin = parseFloat(document.getElementById(\'x-min\').value);
    const xMax = parseFloat(document.getElementById(\'x-max\').value);
    
    const puntosCriticos = [];
    const paso = (xMax - xMin) / 500;
    
    // Encontrar puntos donde f\'(x) ≈ 0
    for (let x = xMin; x <= xMax; x += paso) {
        if (!funcion.dominio(x)) continue;
        
        const fprime = funcion.fprime(x);
        
        if (Math.abs(fprime) < 0.1) {
            // Verificar si es realmente un punto crítico
            const xAnterior = x - paso;
            const xSiguiente = x + paso;
            
            if (funcion.dominio(xAnterior) && funcion.dominio(xSiguiente)) {
                const fprimeAnterior = funcion.fprime(xAnterior);
                const fprimeSiguiente = funcion.fprime(xSiguiente);
                
                if (Math.sign(fprimeAnterior) !== Math.sign(fprimeSiguiente)) {
                    // Buscar punto exacto
                    const xExacto = encontrarCeroPorBiseccion(
                        xAnterior, xSiguiente,
                        xTest => funcion.fprime(xTest),
                        0.001
                    );
                    
                    if (xExacto !== null) {
                        const tipo = clasificarPuntoCritico(funcion, xExacto);
                        puntosCriticos.push({
                            x: parseFloat(xExacto.toFixed(3)),
                            tipo: tipo,
                            f: parseFloat(funcion.f(xExacto).toFixed(3)),
                            fprime2: parseFloat(funcion.fprime2(xExacto).toFixed(3))
                        });
                    }
                }
            }
        }
    }
    
    // Mostrar resultados
    let html = \'<strong>Puntos Críticos Encontrados:</strong><br>\';
    
