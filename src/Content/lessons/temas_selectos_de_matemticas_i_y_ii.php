function verificarPaso(paso) {
    const textarea = document.querySelector(`.paso-solucion[data-paso="${paso}"] .solucion-textarea`);
    const respuesta = textarea.value.trim().toLowerCase();
    
    const soluciones = {
        1: ["4x^3 - 12x^2", "12x^2 - 24x"],
        2: ["x=0", "x=3"],
        3: ["cóncava arriba (-∞,0) u (2,∞)", "cóncava abajo (0,2)"],
        4: ["x=0", "x=2"],
        5: ["x=0: f\'\'=0 indeterminado", "x=3: f\'\'=36 > 0 mínimo"]
    };
    
    let correcto = false;
    soluciones[paso].forEach(sol => {
        if (respuesta.includes(sol.toLowerCase().replace(/[^a-z0-9=()]/g, \'\'))) {
            correcto = true;
